/**
 * How each spring-cleaning job is done: March 2027's "How We Do Our Jobs" (the back of Our Family Spring Clean,
 * docs/club/WELCOME_MARCH_DECEMBER_MIGRATION.md → Phase 3). One guide per job in the Family Spring Cleaning Builder's
 * library (src/data/spring-cleaning.ts), keyed by its stable job id: the library says WHAT the job is, who can safely do
 * it and how long it takes; this says HOW, in the doer's own words. Only the jobs on a family's plan are printed.
 *
 * Each guide: GET READY (what to gather), DO THE JOB (two or three steps), FINISHED WHEN (something anyone can see), an
 * optional safety line, and one approved black-and-white hand-drawn icon (the March chore set, assets/icons/ofc/march/,
 * or the Club icon library, public/images/club/icon-library/). Words are written for the person doing the job; a
 * child's job never asks for a cleaning product (jobs that need one are grown-ups only in the library, or say who hands
 * it over). The safety notes from March's earlier Spring Prep page are carried into the matching jobs here.
 */
