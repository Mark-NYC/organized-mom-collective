export type GuideIcon = { set: 'march'; name: string } | { set: 'library'; name: string };

export interface JobGuide {
  icon: GuideIcon;
  ready: string;
  steps: [string, string] | [string, string, string];
  finished: string;
  /** Who does what for safety (a grown-up's part, a supervised step). */
  safety?: string;
}

