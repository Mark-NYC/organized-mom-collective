/**
 * Writes the January Family Meeting companion for each test household as Markdown (docs/club/samples/), so the content
 * can be read without a browser: `npx vite-node scripts/meeting-guide-samples.ts`. Made-up families.
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { january2027 } from '../src/data/club/meeting-guides/2027-01';
import { generateMeetingGuide } from '../src/lib/club/meeting-guide/generate';
import { FAMILIES } from '../tests/fixtures/meeting-guide-families';

const out = 'docs/club/samples';
mkdirSync(out, { recursive: true });
for (const f of readdirSync(out)) if (f.startsWith('january-meeting-')) rmSync(`${out}/${f}`);
for (const f of FAMILIES) {
  const g = generateMeetingGuide({ household: f.household, profile: f.profile, content: january2027 });
  const head = (i: number) => `### ${g.sections[i].n}. ${g.sections[i].title}\n_${g.sections[i].goal}_\n`;
  const md = [
    `# ${g.title}`,
    `**January 2027 · ${g.familyName}**`,
    '',
    `> Sample: ${f.label}. Generated by \`scripts/meeting-guide-samples.ts\`.`,
    '',
    g.subtitle,
    '',
    `_${g.howTo}_`,
    '',
    head(0),
    ...g.focus.map((x) => `- **${x.title}**${x.opportunity ? ` · ${x.opportunity}` : ''}`),
    '',
    head(1),
    '**Conversation starters**',
    ...g.talk.map((t) => `- ${t.text}`),
    ...(g.talkLittle ? ['', `_${g.talkLittle}_`] : []),
    '',
    '---',
    '',
    head(2),
    `_Ideas to choose from, not jobs. Decide together._`,
    '',
    ...g.people.filter((p) => p.ideas.length || p.keeps).map((p) => {
      const who = `**${p.name}**${p.age !== null ? ` · ${p.age}` : ''}`;
      if (!p.ideas.length) return `- ${who}: ${p.keeps}`;
      return `- ${who}: ${p.choose ? `_${p.name} chooses one:_ ` : ''}${p.ideas.map((i) => i.text).join(' **or** ')} _(${p.support})_${p.keeps ? ` · ${p.keeps}` : ''}`;
    }),
    ...(g.partsDiscover ? [`- ${g.partsDiscover}`] : []),
    ...g.grownUps.map((t) => `- ${t.text}`),
    '',
    head(3),
    '**Ways to make it stick**',
    ...g.practice.map((t) => `- ${t.text}`),
    '',
    `**Coming back to it:** ${g.checkIn}`,
    '',
    '---',
    `_Personalized from: ${g.used.join(', ')}${g.missing.length ? ` · the month’s own ideas for: ${g.missing.join(', ')}` : ''}_`,
    '',
  ].join('\n');
  writeFileSync(`${out}/january-meeting-${f.key}.md`, md);
}
console.log('written');
