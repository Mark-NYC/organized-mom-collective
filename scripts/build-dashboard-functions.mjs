/**
 * Builds one self-contained file per shop Edge Function, for pasting into the Supabase
 * dashboard's browser editor (Edge Functions → Deploy a new function → Via Editor), which
 * can't see the shared modules in supabase/functions/_shared/.
 *
 *   npm run build:functions      writes supabase/dashboard/<function-name>.ts
 *
 * The output is generated: edit the sources in supabase/functions/, then rebuild.
 * tests/shop.test.ts fails if a committed file is out of date. How to deploy: supabase/SHOP.md.
 */
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

export const DASHBOARD_FUNCTIONS = [
  { name: 'shop-checkout', handler: 'createCheckoutHandler', module: 'checkout' },
  { name: 'stripe-webhook', handler: 'createWebhookHandler', module: 'webhook' },
  { name: 'shop-admin', handler: 'createAdminHandler', module: 'admin' },
];

const header = (name) => `// Supabase Edge Function "${name}" — ONE FILE, ready to paste into the dashboard editor.
// GENERATED by scripts/build-dashboard-functions.mjs from supabase/functions/. Do not edit here:
// change the sources, run \`npm run build:functions\`, and paste the new file.
// Deploy: Supabase → Edge Functions → Deploy a new function → Via Editor → name it "${name}",
// replace the editor's contents with this whole file, deploy, then turn OFF "Verify JWT".
// Setup and secrets: supabase/SHOP.md.
`;

/** Bundles one function to a string (no files written). */
export async function bundle(fn) {
  const result = await build({
    stdin: {
      contents: `import { depsFromEnv } from './functions/_shared/deps.ts';
import { ${fn.handler} } from './functions/_shared/handlers/${fn.module}.ts';
Deno.serve(${fn.handler}(depsFromEnv((key) => Deno.env.get(key))));
`,
      resolveDir: join(root, 'supabase'),
      sourcefile: `${fn.name}/index.ts`,
      loader: 'ts',
    },
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'neutral',
    target: 'es2022',
    charset: 'utf8',
    legalComments: 'none',
    logLevel: 'silent',
  });
  return header(fn.name) + result.outputFiles[0].text;
}

export const outputPath = (fn) => join(root, 'supabase', 'dashboard', `${fn.name}.ts`);

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(join(root, 'supabase', 'dashboard'), { recursive: true });
  for (const fn of DASHBOARD_FUNCTIONS) {
    const code = await bundle(fn);
    writeFileSync(outputPath(fn), code);
    console.log(`✓ supabase/dashboard/${fn.name}.ts (${code.split('\n').length} lines)`);
  }
}
