/**
 * The January companion's quality report: for each test family, the opportunity chosen, the intake evidence, why it
 * won, what's recommended, how it can become a habit, how it builds ownership, what was left out, and the editorial
 * scorecard (A grounded, B focus, C age, D actionable habit, E ownership, F low overwhelm; 0–2 each, pass ≥ 10 with
 * no zero in A, D or E). The scores are computed by fixed rules from the generated companion, so they can't be nudged;
 * they're an editorial gate, not proof anything works in a real home.
 *
 *   npx vite-node scripts/meeting-guide-quality.ts   → docs/club/JANUARY_QUALITY.md
 */
import { writeFileSync } from 'node:fs';
import { january2027 as content } from '../src/data/club/meeting-guides/2027-01';
import { generateMeetingGuide, type MeetingGuide } from '../src/lib/club/meeting-guide/generate';
import { FAMILIES } from '../tests/fixtures/meeting-guide-families';

export function scorecard(g: MeetingGuide) {
  const ex = g.experiments;
  const lines = [...g.focus.map((f) => f.title), ...g.talk.map((t) => t.text), ...ex.flatMap((e) => [e.action, e.ownership, e.support ?? '']), ...g.practice.map((t) => t.text)].filter(Boolean);
  const starter = Boolean(g.starterNote);
  const A = starter ? 1 : ex.every((e) => e.basis === 'need' && e.why) ? 2 : 1;
  const B = g.focus.length === 1 && ex.length <= 2 && g.talk.length <= 3 ? 2 : 1;
  const C = !ex.length ? 1 : ex.every((e) => e.basis === 'need') ? 2 : 1;
  const D = ex.length && ex.every((e) => e.action && e.anchor.text) ? 2 : g.partsDiscover ? 1 : 0;
  const E = (ex.length ? ex.every((e) => e.ownership) : Boolean(g.partsDiscover)) && (g.talk.some((t) => t.key === 'talk:invite') || g.partsDiscover || ex.every((e) => !e.memberIds.length || g.people.find((p) => p.id === e.memberIds[0])?.stage === 'preschool')) ? 2 : 1;
  const F = new Set(lines).size === lines.length && ex.length <= 2 && g.practice.length <= 3 ? 2 : 1;
  const total = A + B + C + D + E + F;
  return { A, B, C, D, E, F, total, pass: total >= 10 && A > 0 && D > 0 && E > 0 };
}

/** The editor's own read of each result, where it differs from or adds to the computed score. */
const REVIEW: Record<string, { score?: number; note: string }> = {
  'preschool-support': { note: 'One experiment, for the child she named: Tobi’s coat-and-shoes habit with the low hook, done together first. Ada (2) joins through Let’s Talk. One is enough here.' },
  'fewer-reminders': { note: 'Two distinct experiments from her two named wishes, both anchored to school nights she confirmed; Mira’s pet care is noticed, not added to.' },
  'mixed-ages': { note: 'Leo’s wished bedroom reset and Jade’s keys-and-chargers spot: two different jobs for two children; Mia (5) is left out on purpose to keep it to two.' },
  'busy-schedules': { note: 'Different from the evening template: Nils’s gear spot (her wish) and Elsa’s calendar-and-rides habit for the schedules focus.' },
  mornings: { note: 'Sofia’s school bag (her wish) and Mateo’s three morning steps (her open wish), with a picture list and the steps put in order by Mateo.' },
  resistance: { note: 'Her own words lead; each child’s own wished job, with a choice of music as the ownership move. “If it gets stuck: let each child choose” is the one adjustment.' },
  independent: { note: 'Grace is recognized and asked to show how; Owen gets the bag habit.' },
  'many-priorities': { note: 'One focus out of six answers; Ben’s bedtime and Ana’s dishes, both her named wishes.' },
  vague: { note: 'Limited by intake (no ages, no answers): only the shared meeting habit; the children are asked later. Not fixable without guessing.' },
  'one-challenge': { note: 'Her challenge doesn’t say which job, so the children are asked which job needs reminders; no experiment is invented. C and D are 1 by design.' },
};

const out: string[] = [
  '# January companion: quality report',
  '',
  'Generated by `scripts/meeting-guide-quality.ts` from `tests/fixtures/meeting-guide-families.ts` (made-up families). Scores are computed by fixed rules from each generated companion. They\'re an editorial quality gate, not evidence that a recommendation will work in a real home.',
  '',
  '| # | Family | Focus chosen | A | B | C | D | E | F | Computed | Editor | Pass |',
  '| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |',
];
const details: string[] = [];
FAMILIES.forEach((f, n) => {
  const g = generateMeetingGuide({ household: f.household, profile: f.profile, content });
  const s = scorecard(g);
  const editor = REVIEW[f.key]?.score ?? s.total;
  out.push(`| ${n + 1} | ${f.label.replace(/^\d+ · /, '')} | ${g.focus.map((x) => x.title).join(' + ')} | ${s.A} | ${s.B} | ${s.C} | ${s.D} | ${s.E} | ${s.F} | **${s.total}** | ${editor} | ${s.pass ? 'yes' : '**no**'} |`);
  const r = g.rationale;
  details.push(
    `## ${f.label}`,
    '',
    `**Highest-impact opportunity:** ${g.focus[0].title}${g.focus[1] ? ` (second: ${g.focus[1].title})` : ''}`,
    '',
    `**Intake evidence:** ${r.focus[0].evidence.length ? r.focus[0].evidence.join('; ') : 'none: no priority, challenge or wish, so the month’s own purpose and discovery questions'}`,
    '',
    `**Why it won:** score ${r.focus[0].score} (relevance ${r.focus[0].parts.relevance}, impact ${r.focus[0].parts.impact}, readiness ${r.focus[0].parts.readiness}, habit ${r.focus[0].parts.habit})${r.considered.length ? `. Also considered: ${r.considered.map((c) => `${c.id} ${c.score}`).join(', ')}.` : '.'}`,
    '',
    '**Habit experiments:**',
    ...g.experiments.map((e) => `- ${e.who} · ${e.title}: “${e.action}” · when: ${e.anchor.text}${e.anchor.verified ? ' (from her answers)' : ' (options to discuss)'} · ownership: ${e.ownership}${e.support ? ` · help: ${e.support}` : ''}${e.basis === 'consider' ? ' · to consider' : ''}`),
    ...(g.partsDiscover ? [`- ${g.partsDiscover}`] : []),
    '',
    `**Why these:** ${g.experiments.map((e) => e.why).filter(Boolean).join(' / ') || 'too little intake for a family-specific need'}.`,
    '',
    `**Left out:** ${[...r.considered.map((c) => `${c.id} (score ${c.score})`), ...r.children.map((c) => `${c.name}: ${c.outcome}`)].join('; ') || 'nothing else applied'}.`,
    '',
    `**Score:** A ${s.A} · B ${s.B} · C ${s.C} · D ${s.D} · E ${s.E} · F ${s.F} = **${s.total}/12** computed${REVIEW[f.key]?.score ? `, **${REVIEW[f.key].score}/12** on review` : ''} ${s.pass ? '(pass)' : '(below standard)'}`,
    '',
    `**Editor’s review:** ${REVIEW[f.key]?.note ?? ''}`,
    '',
  );
});
const WEAKEST = [
  '## What changed in this round',
  '',
  '- Experiments replace general prompts: who, why (her answer), one small action, a moment it could follow, an ownership move and support.',
  '- One or two distinct experiments (different child, different kind of job); never one per child just to include everyone.',
  '- Anchors are options to discuss unless her answers confirm one (school she listed, an activity she named and its days).',
  '- A focus that comes only from her wishes stays with those wishes (the sweep test found a sibling getting an unexplained idea).',
  '- Thin intake: the month’s shared meeting habit, and at most one idea clearly framed as something to consider.',
  '',
];
writeFileSync('docs/club/JANUARY_QUALITY.md', [...out, '', ...WEAKEST, ...details].join('\n'));
